def test_header_row_detection_and_summary():
    csv_bytes = b"Report Generated By System\nTimestamp: 2023-01-01\nID,Customer,Revenue\n1,Acme,500\n2,Beta,750\n"
    hdr_idx = detect_header_row(csv_bytes, delimiter=",")
    assert hdr_idx == 2  # The 3rd line contains "ID,Customer,Revenue"

    meta = {
        "name": "sales.csv",
        "size_bytes": 2048,
        "extension": ".csv",
        "rows": 100,
        "cols": 3,
        "encoding": "UTF-8",
        "delimiter": ",",
    }
    summary = format_plain_language_summary(meta)
    assert "sales.csv" in summary
    assert "100 rows" in summary
    assert "3 columns" in summary
