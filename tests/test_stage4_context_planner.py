def test_domain_detection():
    fin_cols = ["transaction_id", "revenue_amount", "tax_rate", "profit_margin"]
    d_fin, conf_fin = detect_domain(fin_cols)
    assert d_fin == "Finance"
    assert conf_fin > 0.5

    health_cols = ["patient_id", "diagnosis_code", "blood_pressure", "dosage_mg"]
    d_health, conf_health = detect_domain(health_cols)
    assert d_health == "Healthcare"
    assert conf_health > 0.5

    ecom_cols = ["order_id", "sku_code", "unit_price", "shipping_address"]
    d_ecom, conf_ecom = detect_domain(ecom_cols)
    assert d_ecom == "E-Commerce"
    assert conf_ecom > 0.5

    generic_cols = ["x1", "x2", "x3"]
    d_gen, conf_gen = detect_domain(generic_cols)
    assert d_gen == "General"


