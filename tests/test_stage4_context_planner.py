def test_action_plan_ml_priorities():
    df = pd.DataFrame({
        "customer id": [1, 2, 2, 3, 4],  # duplicate row + non-snake-case
        "monthly spend": ["$100", "$200", "$200", "$300", "$15000"],  # string currency + outlier
        "churn": [0, 0, 0, 0, 1],  # target class
        "empty_feature": [np.nan, np.nan, np.nan, np.nan, np.nan],  # empty col
    })

    ctx = UserContext(goal="ml", target_column="churn", domain="SaaS & Tech")
    plan = create_action_plan(df, context=ctx)

    assert isinstance(plan, ActionPlan)
    assert plan.goal == "ml"
    assert plan.initial_quality_score <= 100.0
    assert len(plan.actions) > 0

    operations = [a.operation for a in plan.actions]
    assert "drop_empty_columns" in operations
    assert "snake_case_columns" in operations
    assert "convert_numeric_text" in operations
    assert "remove_duplicates" in operations

    # Duplicates in ML have CRITICAL severity
    dup_action = next(a for a in plan.actions if a.operation == "remove_duplicates")
    assert dup_action.severity == "CRITICAL"
    assert dup_action.risk == "safe"
    assert isinstance(dup_action.score_impact, float)

    # Safe actions subset
    safe = plan.safe_actions()
    assert len(safe) > 0
    assert all(a.risk == "safe" for a in safe)


